import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { clean, parseCsv, safeEmail, safePhone, safeWebsite, validDate } from '../src/lib/directory/normalize.ts';
import { directory, deduplicate, normalizeSchool, relatedSchools, applyCorrections, sourceLabel } from '../src/lib/directory/data.ts';
import { filterSchools, searchText } from '../src/lib/directory/search.ts';

assert.equal(clean(' null '), undefined);
assert.equal(clean('a\u0000\n b'), 'a b');
assert.equal(safeWebsite('example.sch.id'), 'https://example.sch.id/');
for (const value of ['javascript:alert(1)', 'data:text/html,x', 'https://user:pass@example.com', 'not a host', '//evil.example', 'https://localhost', 'https://example.com\n.evil.com']) assert.equal(safeWebsite(value), undefined, value);
assert.equal(safePhone('0812-3456-7890'), '+6281234567890');
assert.equal(safePhone('(0413) 123456'), '+62413123456');
assert.equal(safePhone('123'), undefined);
assert.equal(safeEmail('school@example.sch.id'), 'school@example.sch.id');
assert.equal(safeEmail('a@example..com'), undefined);
assert.equal(safeEmail('x@example.com?subject=spam'), undefined);
assert.ok(validDate('2026-02-28'));
assert.ok(!validDate('2026-02-30'));
assert.ok(!validDate('2026-99-99'));
assert.equal(sourceLabel({ sourceName: 'Dapodik Kemendikdasmen', sourceUpdatedAt: '2026-10-06' }), 'Data per 6 Okt 2026 · Sumber: Dapodik Kemendikdasmen');
assert.equal(sourceLabel({ sourceName: 'Dapodik Kemendikdasmen', sourceUpdatedAt: '2026-10-08' }), 'Data per 8 Okt 2026 · Sumber: Dapodik Kemendikdasmen');
assert.equal(sourceLabel({ sourceName: 'Sumber contoh', sourceUpdatedAt: '2026-01-01' }), 'Data per 1 Jan 2026 · Sumber: Sumber contoh');
assert.equal(sourceLabel({ sourceName: 'Sumber contoh', sourceUpdatedAt: null }), 'Tanggal pembaruan sumber tidak tersedia · Sumber: Sumber contoh');

const csv = '\uFEFFnpsn,nama,bentuk_pendidikan,kabupaten\r\n00000001,"Sekolah, \"\"Contoh\"\"\nBaru",SD,Kab. Bantaeng\r\n';
assert.equal(parseCsv(csv)[0].nama, 'Sekolah, "Contoh"\nBaru');
assert.throws(() => parseCsv('npsn,nama\n1,test'), /kolom wajib/);
assert.throws(() => parseCsv('npsn,nama,bentuk_pendidikan,kabupaten\n1,"broken,SD,X'), /kutipan/);
assert.throws(() => parseCsv('npsn,nama,bentuk_pendidikan,kabupaten\n1,"name"oops,SD,X'), /kutipan/);
assert.throws(() => parseCsv('npsn,nama,bentuk_pendidikan,kabupaten\n1,test,SD,X,extra'), /jumlah kolom/);

const dataset = { ...directory.datasets[0], format: 'prototype-json', regency: 'Kabupaten Bantaeng', regencySlug: 'bantaeng' };
const sample = parseCsv(readFileSync('data/directory/sample-sekolah.csv', 'utf8')).map(row => normalizeSchool(row, { ...dataset, format: 'csv' }));
assert.equal(sample.length, 20);
assert.ok(sample.some(school => school.npsn === 'K9997941' && school.path.endsWith('/k9997941')));
assert.equal(normalizeSchool({ npsn: '00000001', nama: 'Contoh', bentuk: 'SD' }, dataset).npsn, '00000001');
assert.throws(() => normalizeSchool({ npsn: '123', nama: 'Contoh', bentuk: 'SD' }, dataset), /Identitas/);
assert.throws(() => normalizeSchool({ npsn: '00000001', nama: 'Contoh', bentuk: 'OTHER' }, dataset), /Identitas/);
assert.throws(() => normalizeSchool({ npsn: '00000001', nama: 'Contoh', bentuk_pendidikan: 'SD', kabupaten: 'Kota Lain' }, { ...dataset, format: 'csv' }), /Wilayah/);
const provinceDataset = { ...directory.datasets[0], format: 'csv', regency: undefined, regencySlug: undefined };
const acrossRegions = ['Kab. Bantaeng', 'Kota Makassar', 'Kab. Pangkajene Dan Kepulauan'].map(kabupaten => normalizeSchool({ npsn: '00000001', nama: 'Contoh', bentuk_pendidikan: 'PDF Ulya', kabupaten }, provinceDataset));
assert.deepEqual(acrossRegions.map(school => school.regencySlug), ['bantaeng', 'makassar', 'pangkajene-dan-kepulauan']);
assert.deepEqual(acrossRegions.map(school => school.regency), ['Kabupaten Bantaeng', 'Kota Makassar', 'Kabupaten Pangkajene Dan Kepulauan']);
assert.deepEqual(acrossRegions.map(school => school.path), ['/sekolah/sulawesi-selatan/bantaeng/00000001', '/sekolah/sulawesi-selatan/makassar/00000001', '/sekolah/sulawesi-selatan/pangkajene-dan-kepulauan/00000001']);
assert.throws(() => normalizeSchool({ npsn: '00000001', nama: 'Contoh', bentuk_pendidikan: 'SD' }, provinceDataset), /Wilayah/);
assert.throws(() => normalizeSchool({ npsn: '00000001', nama: 'Contoh', bentuk_pendidikan: 'SD', kabupaten: 'Bantaeng' }, provinceDataset), /Wilayah/);
const incoming = directory.datasets.map(source => {
  const text = readFileSync(`data/directory/${source.file}`, 'utf8');
  return { source, ids: new Set((source.format === 'csv' ? parseCsv(text) : JSON.parse(text)).map(row => clean(row.npsn)?.toUpperCase())) };
});
const expectedIds = new Set(incoming.flatMap(dataset => [...dataset.ids]));
assert.deepEqual(directory.schools.map(school => school.npsn).sort(), [...expectedIds].sort());
for (const { source, ids } of incoming) {
  const schools = directory.schools.filter(school => ids.has(school.npsn));
  assert.equal(schools.length, ids.size);
  assert.ok(schools.every(school => school.provinceSlug === source.provinceSlug && school.sourceUpdatedAt === clean(source.sourceUpdatedAt)));
}
const importedPaths = new Set(directory.schools.map(school => school.path));
for (const school of JSON.parse(readFileSync('data/directory/bantaeng-pilot.json', 'utf8'))) assert.ok(importedPaths.has(normalizeSchool(school, dataset).path), `Pilot URL retained: ${school.npsn}`);
assert.equal(deduplicate([sample[0], sample[0]]).duplicates, 1);
assert.throws(() => deduplicate([sample[0], { ...sample[0], name: 'Sekolah Berbeda' }]), /berkonflik/);
assert.equal(normalizeSchool({ npsn: '00000001', nama: 'Contoh', bentuk: 'SD', telepon: '081234567890', email: 'x@example.com' }, { ...dataset, contactsApproved: false }).phone, undefined);
const fixture = normalizeSchool({ npsn: '00000001', nama: 'Sekolah Contoh', bentuk: 'SD', website: 'example.sch.id' }, dataset);
const correction = { npsn: fixture.npsn, reason: 'Bukti fixture terverifikasi', verifiedAt: '2026-10-11', fields: { address: 'Alamat fixture', website: null } };
assert.equal(applyCorrections([fixture], [correction]), 1);
assert.equal(fixture.address, 'Alamat fixture');
assert.equal(fixture.website, undefined);
assert.throws(() => applyCorrections([fixture], [{ ...correction, verifiedAt: '2026-02-30' }]), /Koreksi tidak valid/);
assert.throws(() => applyCorrections([fixture], [{ ...correction, fields: { path: '/unsafe' } }]), /tidak diizinkan/);
assert.throws(() => applyCorrections([fixture], [{ ...correction, fields: { website: 'javascript:alert(1)' } }]), /Nilai koreksi/);
assert.throws(() => applyCorrections([{ ...fixture, contactsApproved: false }], [{ ...correction, fields: { email: 'fixture@example.com' } }]), /belum disetujui/);
assert.throws(() => applyCorrections([fixture], [correction, correction]), /Koreksi tidak valid/);
assert.ok(directory.schools.length >= sample.length);
assert.equal(new Set(directory.schools.map(school => school.path)).size, directory.schools.length);
for (const school of directory.schools) assert.ok(relatedSchools(school).every(related => related.npsn !== school.npsn && related.regencySlug === school.regencySlug && related.provinceSlug === school.provinceSlug));
assert.equal(searchText('Pa`jukukang'), 'pajukukang');
const records = directory.schools;
assert.ok(filterSchools(records, 'smk pgri').some(school => school.npsn === '69988522'));
assert.equal(filterSchools(records, 'K9997941')[0].npsn, 'K9997941');
const combined = filterSchools(records, '', 'SMK', 'Bantaeng');
assert.ok(combined.length > 0 && combined.every(school => school.educationLevel === 'SMK' && school.district === 'Bantaeng'));
assert.equal(filterSchools(records, 'nama-fixture-tidak-ada').length, 0);
console.log('Directory data checks passed: CSV, identifiers, contacts, deduplication, search, and combined filters.');
